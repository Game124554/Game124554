"""Generates FormData.java and ScientistData.java from spec.py"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from spec import FORMS, SCIENTISTS

ROOT = os.path.join(os.path.dirname(__file__), "..", "src/main/java/com/latexdrone/content")
os.makedirs(ROOT, exist_ok=True)

def rgb(c):
    return "0x%02X%02X%02X" % c

lines = []
for i, f in enumerate(FORMS):
    lines.append(
        f'        new LatexForm({i}, "{f["id"]}", "{f["name"]}", {rgb(f["primary"])}, {rgb(f["secondary"])}, {rgb(f["glow"])}, '
        f'{f["parts"]}, {f["scale"]}f, {float(f["hp"])}, {float(f["dmg"])}, {f["speed"]}, {float(f["armor"])}, {float(f["infect"])}f, '
        f'"{f["ability"]}", "{f["sound"]}", {f["weight"]})')
with open(os.path.join(ROOT, "FormData.java"), "w") as fh:
    fh.write("""// GENERATED by tools/gen_java.py - edit tools/spec.py instead
package com.latexdrone.content;

import java.util.List;

public final class FormData {
    private FormData() {}

    public static final List<LatexForm> FORMS = List.of(
""" + ",\n".join(lines) + """
    );
}
""")

lines = []
for i, s in enumerate(SCIENTISTS):
    lines.append(
        f'        new ScientistType({i}, "{s["id"]}", "{s["name"]}", "{s["species"]}", {rgb(s["fur"])}, {rgb(s["fur2"])}, {rgb(s["glow"])}, '
        f'{s["parts"]}, "{s["weapon"]}", {"true" if s["ranged"] else "false"}, {float(s["hp"])})')
with open(os.path.join(ROOT, "ScientistData.java"), "w") as fh:
    fh.write("""// GENERATED by tools/gen_java.py - edit tools/spec.py instead
package com.latexdrone.content;

import java.util.List;

public final class ScientistData {
    private ScientistData() {}

    public static final List<ScientistType> SCIENTISTS = List.of(
""" + ",\n".join(lines) + """
    );
}
""")
print("java data generated")
