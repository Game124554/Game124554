    /** layer: 0 = solid, 1 = cutout, 2 = translucent. */
    private static Block register(String name, Block block, int layer) {
        Registry.register(BuiltInRegistries.BLOCK, LatexDrones.id(name), block);
        Item item = Registry.register(BuiltInRegistries.ITEM, LatexDrones.id(name), new BlockItem(block, new Item.Properties()));
        ALL.add(block);
        ITEMS.add(item);
        if (layer == 1) {
            CUTOUT.add(block);
        } else if (layer == 2) {
            TRANSLUCENT.add(block);
        }
        return block;
    }

